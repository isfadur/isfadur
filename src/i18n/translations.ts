export function getCategoryName(category: string, lang: Language): string {
  if (categoryTranslations[category]) {
    return categoryTranslations[category][lang];
  }
  return category;
}

export function getConditionName(condition: string, lang: Language): string {
  if (lang === 'bn') {
    if (condition === 'Brand New') return 'একদম নতুন';
    if (condition === 'Like New') return 'নতুনের মতো';
    if (condition === 'Used') return 'ব্যবহৃত';
    if (condition === 'Not Applicable') return 'প্রযোজ্য নয়';
  }
  return condition;
}
